def para(text, bold=False, italic=False, after=4, keep=False):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.bold, r.italic = bold, italic
    p.paragraph_format.space_after = Pt(after)
    p.paragraph_format.keep_with_next = keep
    return p


def shot(path, caption, max_w=16.5, max_h=11.0):
    if path is None:
        return
    with Image.open(path) as im:
        ratio = im.width / im.height
    w = min(max_w, max_h * ratio)
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.keep_with_next = True
    p.paragraph_format.space_after = Pt(2)
    p.add_run().add_picture(str(path), width=Cm(w))
    fig_n[0] += 1
    c = doc.add_paragraph()
    c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    c.add_run(f"Рисунок {fig_n[0]} – {caption}").italic = True
    c.paragraph_format.space_after = Pt(8)


