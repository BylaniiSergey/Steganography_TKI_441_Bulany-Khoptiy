def trim_right_black(im):
    """Убирает чёрную полосу справа от окна фигуры (след DPI-масштабирования)."""
    px = im.convert("RGB")
    w, h = px.size
    cut = w
    while cut > w * 0.9:
        col = [px.getpixel((cut - 1, y)) for y in range(0, h, max(1, h // 40))]
        if all(sum(c) < 30 for c in col):
            cut -= 1
        else:
            break
    return im.crop((0, 0, cut, h))


def prep(n, kind, name):
    """Копирует снимок в итоговую папку с понятным именем; возвращает путь или None."""
    src = SHOTS / f"shot_{n:02d}_{kind}.png"
    if not src.exists():
        return None
    im = Image.open(src).convert("RGB")
    if kind.startswith("fig"):
        im = trim_right_black(im)
        if im.width > 2200:
            im = im.resize((2200, int(im.height * 2200 / im.width)), Image.Resampling.LANCZOS)
    dst = OUTDIR / f"{n:02d}_{name}_{'окно_рисунка' if kind.startswith('fig') else 'консоль'}.png"
    im.save(dst)
    return dst


